#!/usr/bin/env node

/**
 * Generates `src/components/Atom/icon/icon-name.ts` — the `IconName` union —
 * from whatever @tabler/icons-react is installed.
 *
 *   pnpm --filter @rakit-ui/ui icons
 *   pnpm --filter @rakit-ui/ui icons:check   # CI: fail if out of date
 *
 * `icon-registry.ts` builds its keys at runtime from the same export list using
 * the same transform. Generating the union from that list rather than hand-
 * writing it is what keeps the compile-time names and the runtime keys in step;
 * `--check` is what stops them drifting after a Tabler upgrade.
 *
 * The union is not derived from Tabler's own kebab names on purpose. Those are
 * carried inside each module (`createReactComponent("outline", "a-b-2", …)`)
 * and do not always match a mechanical transform of the export name — `IconAB2`
 * is `a-b-2` there but `ab2` here. Following the export names keeps one rule.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, "..");
const OUTPUT_PATH = join(packageRoot, "src/components/Atom/icon/icon-name.ts");

const check = process.argv.includes("--check");

function fail(message) {
  process.stderr.write(`\n  icons: ${message}\n\n`);
  process.exit(1);
}

/** Must stay identical to `toIconName` in icon-registry.ts. */
function toIconName(exportName) {
  return exportName
    .replace(/^Icon/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

const TablerIcons = await import("@tabler/icons-react").catch(() =>
  fail("could not import @tabler/icons-react — is it installed?"),
);

const version = JSON.parse(
  readFileSync(join(packageRoot, "node_modules/@tabler/icons-react/package.json"), "utf8"),
).version;

/*
 * Same filter as the registry: the barrel also exports `createReactComponent`,
 * `icons`, `iconsList` and `default`. Without the prefix test, `name="icons"`
 * would typecheck and then render nothing.
 */
const names = Object.entries(TablerIcons)
  .filter(([key, value]) => key.startsWith("Icon") && typeof value === "object" && value !== null)
  .map(([key]) => toIconName(key));

const unique = [...new Set(names)].sort();
if (unique.length === 0) {
  fail("found 0 icons — the package layout may have changed");
}

const next = `// GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Source: @tabler/icons-react v${version} (${unique.length} icons).
// Run \`pnpm --filter @rakit-ui/ui icons\` after upgrading Tabler.

export type IconName =
${unique.map((name) => `  | "${name}"`).join("\n")};
`;

const current = (() => {
  try {
    return readFileSync(OUTPUT_PATH, "utf8");
  } catch {
    return null;
  }
})();

if (check) {
  if (current !== next) {
    fail("icon-name.ts is out of date. Run `pnpm --filter @rakit-ui/ui icons`.");
  }
  process.stdout.write(`icons: up to date (${unique.length} names)\n`);
} else if (current === next) {
  process.stdout.write(`icons: no change (${unique.length} names)\n`);
} else {
  writeFileSync(OUTPUT_PATH, next);
  process.stdout.write(`icons: wrote icon-name.ts (${unique.length} names)\n`);
}
